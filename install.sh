#!/usr/bin/env bash
# Releasesmith - project-level setup. Runs unprivileged, installs Python
# packages into the current interpreter, creates the database and seeds demo
# data, then EXITS. It never starts the HTTP server.
set -euo pipefail
cd "$(dirname "$0")"

PYTHON="${PYTHON:-python3}"

echo "==> Checking the Python interpreter"
"$PYTHON" -c 'import sys; assert sys.version_info >= (3, 11), "Python 3.11+ is required"'

echo "==> Installing Python dependencies"
"$PYTHON" -m pip install --upgrade pip setuptools wheel
"$PYTHON" -m pip install -r requirements.txt

echo "==> Preparing .env"
if [ -f .env ]; then
  echo "    .env already exists - leaving it untouched"
else
  SECRET="$("$PYTHON" -c 'import secrets; print(secrets.token_hex(32))')"
  {
    printf '# Generated by install.sh on first run.\n'
    printf 'SECRET_KEY=%s\n' "$SECRET"
    printf 'DATABASE_URL=sqlite:///./releasesmith.db\n'
  } > .env
  echo "    wrote .env with a freshly generated SECRET_KEY"
fi

echo "==> Creating the database schema and seeding demo data"
"$PYTHON" -m app.seed

echo "==> Import self-check"
"$PYTHON" -c 'import app.main; assert app.main.app is not None'

cat <<'MSG'

Setup complete. Start the app with:

  uvicorn app.main:app --host 0.0.0.0 --port "${PORT:-8000}"

Then open http://localhost:8000 and sign in with the demo account:
  cenius@cenius.ai / cenius
MSG
